public class Person {
    
    private  String name;
    private int age;
    private  String id;


    //getters

    public String getName(){
        return name;
    }
    public int getAge(){
        return age;
    }
    public String getId(){
        return id;
    }


    //setters
    public void setName(String name){
        this.name = name;  
    }
    public void setAge(int age){
        this.age = age;
    }
    public void setId(String id){
        this.id = id;
    }
}
